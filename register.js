
"use strict";

/*
 * TIT CBT Examination Portal
 * Candidate Registration
 *
 * DEMO VERSION:
 * Data is saved in this browser only.
 * Do not use for real candidate records until
 * a secure backend/database is connected.
 */

const registrationForm = document.getElementById("registrationForm");
const candidateNameInput = document.getElementById("candidateName");
const fatherNameInput = document.getElementById("fatherName");
const classInput = document.getElementById("candidateClass");
const mobileInput = document.getElementById("mobileNumber");
const dobInput = document.getElementById("dob");

const formError = document.getElementById("formError");
const successSection = document.getElementById("registrationSuccess");
const registerButton = document.getElementById("registerButton");

const generatedRegNo = document.getElementById("generatedRegNo");
const generatedClass = document.getElementById("generatedClass");
const registrationOk = document.getElementById("registrationOk");

document.getElementById("currentYear").textContent =
    new Date().getFullYear();

/* Prevent future dates of birth. */
dobInput.max = new Date().toISOString().split("T")[0];

/* Automatically convert names to uppercase. */
function uppercaseName(input) {
    input.addEventListener("input", function () {
        const start = input.selectionStart;
        const end = input.selectionEnd;

        input.value = input.value.toLocaleUpperCase("en-IN");

        try {
            input.setSelectionRange(start, end);
        } catch (_) {
            // Some input states do not support cursor restoration.
        }
    });
}

uppercaseName(candidateNameInput);
uppercaseName(fatherNameInput);

/* Allow digits only; maximum 10 digits. */
mobileInput.addEventListener("input", function () {
    mobileInput.value = mobileInput.value
        .replace(/\D/g, "")
        .slice(0, 10);
});

/* Show a registration error. */
function showError(message) {
    formError.textContent = message;
    formError.hidden = false;
}

/* Hide registration errors. */
function clearError() {
    formError.textContent = "";
    formError.hidden = true;
}

/* Validate date of birth. */
function isValidDOB(value) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) {
        return false;
    }

    const date = new Date(value + "T00:00:00");

    if (Number.isNaN(date.getTime())) {
        return false;
    }

    const today = new Date();
    today.setHours(0, 0, 0, 0);

    return date <= today &&
        date.toISOString().slice(0, 10) === value;
}

/*
 * Demo registration number generator.
 * Real production IDs must be generated by the server.
 */
function generateRegistrationNumber(existingCandidates) {
    let registrationNumber;

    do {
        const randomNumber = Math.floor(
            100000 + Math.random() * 900000
        );

        registrationNumber = "TIT-" +
            new Date().getFullYear() + "-" +
            randomNumber;

    } while (
        existingCandidates.some(
            candidate =>
                candidate.registrationNumber === registrationNumber
        )
    );

    return registrationNumber;
}

/* Safely read the existing demo registrations. */
function readCandidates() {
    const saved = localStorage.getItem("TIT_CANDIDATES");

    if (!saved) {
        return [];
    }

    try {
        const parsed = JSON.parse(saved);

        if (!Array.isArray(parsed)) {
            throw new Error("Invalid registration data");
        }

        return parsed;
    } catch (error) {
        throw new Error(
            "Saved registration data could not be read. " +
            "Please contact the administrator."
        );
    }
}

/* Handle registration. */
registrationForm.addEventListener("submit", function (event) {
    event.preventDefault();
    clearError();

    const candidateName = candidateNameInput.value.trim()
        .toLocaleUpperCase("en-IN");

    const fatherName = fatherNameInput.value.trim()
        .toLocaleUpperCase("en-IN");

    const candidateClass = classInput.value;
    const mobileNumber = mobileInput.value;
    const dob = dobInput.value;

    if (!candidateName || !fatherName) {
        showError("Please enter the candidate's and father's name.");
        return;
    }

    if (!["10th", "12th Science", "12th Arts"].includes(candidateClass)) {
        showError("Please select a valid class.");
        return;
    }

    if (!/^[6-9]\d{9}$/.test(mobileNumber)) {
        showError(
            "Enter a valid 10-digit Indian mobile number beginning with 6, 7, 8 or 9."
        );
        mobileInput.focus();
        return;
    }

    if (!isValidDOB(dob)) {
        showError("Please enter a valid date of birth.");
        dobInput.focus();
        return;
    }

    registerButton.disabled = true;
    registerButton.textContent = "Registering...";

    try {
        const candidates = readCandidates();

        /*
         * Prevent duplicate registrations using the same mobile
         * number in this browser's demo data.
         */
        const duplicate = candidates.some(
            candidate => candidate.mobileNumber === mobileNumber
        );

        if (duplicate) {
            showError(
                "This mobile number is already registered in this browser. " +
                "Please use Sign In if you have already registered."
            );
            return;
        }

        const registrationNumber =
            generateRegistrationNumber(candidates);

        /*
         * IMPORTANT:
         * This demo object contains DOB for testing only.
         * Production systems must not store DOB as plaintext password.
         */
        const candidate = {
            registrationNumber: registrationNumber,
            candidateName: candidateName,
            fatherName: fatherName,
            candidateClass: candidateClass,
            mobileNumber: mobileNumber,
            dob: dob,
            registrationDate: new Date().toISOString(),
            examStatus: "NOT_ATTEMPTED"
        };

        candidates.push(candidate);

        localStorage.setItem(
            "TIT_CANDIDATES",
            JSON.stringify(candidates)
        );

        /* Save only the current demo candidate reference. */
        localStorage.setItem(
            "TIT_CURRENT_REGISTRATION",
            registrationNumber
        );

        registrationForm.hidden = true;
        successSection.hidden = false;

        generatedRegNo.textContent = registrationNumber;
        generatedClass.textContent = candidateClass;

    } catch (error) {
        showError(
            error.message ||
            "Registration failed. Please try again."
        );
    } finally {
        registerButton.disabled = false;
        registerButton.textContent = "Register Now →";
    }
});

/* Continue to the candidate login page. */
registrationOk.addEventListener("click", function () {
    window.location.href = "login.html";
});
